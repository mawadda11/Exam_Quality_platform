def requirement_name(identifier: str, original: str, language: ReportLanguage) -> str:
    if language is ReportLanguage.ARABIC:
        return REQUIREMENT_NAMES_AR.get(identifier, "متطلب تقييم محكوم")
    return original


def governed_label(original: str, language: ReportLanguage) -> str:
    if language is ReportLanguage.ARABIC:
        return GOVERNED_LABELS_AR.get(original, "بيان محكوم")
    return original


def finding_explanation(status: AcademicStatus, original: str, language: ReportLanguage) -> str:
    if language is ReportLanguage.ARABIC:
        return STATUS_EXPLANATIONS_AR[status]
    return original


def recommendation_text(
    identifier: str,
    title: str,
    text: str,
    language: ReportLanguage,
) -> tuple[str, str]:
    if language is ReportLanguage.ARABIC:
        return RECOMMENDATIONS_AR.get(
            identifier,
            ("راجع التوصية المرتبطة", "راجع نتيجة التقييم والأدلة واتخذ الإجراء المناسب."),
        )
    return title, text
